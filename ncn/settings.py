def _parse_cloudinary_url():
    """Build CLOUDINARY_STORAGE dict from CLOUDINARY_URL (no secrets in code)."""
    url = os.environ.get("CLOUDINARY_URL", "").strip()
    if not url.startswith("cloudinary://"):
        return {}
    parsed = urlparse(url)
    cloud_name = (parsed.hostname or "").strip()
    api_key = unquote(parsed.username or "")
    api_secret = unquote(parsed.password or "")
    if not all((cloud_name, api_key, api_secret)):
        return {}
    return {
        "CLOUD_NAME": cloud_name,
        "API_KEY": api_key,
        "API_SECRET": api_secret,
    }


CLOUDINARY_STORAGE = _parse_cloudinary_url()
USE_CLOUDINARY_MEDIA = bool(CLOUDINARY_STORAGE.get("CLOUD_NAME"))

def _env_bool(name, default=False):
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in ("1", "true", "yes", "on")


def _env_list(name, default=None):
    raw = os.environ.get(name, "").strip()
    if not raw:
        return list(default or [])
    return [item.strip() for item in raw.split(",") if item.strip()]


